import { test, expect } from '@playwright/test';
import {assertGameFits} from './layout-assertions.js';
import { PNG } from 'pngjs';
import { readFileSync,writeFileSync,mkdirSync,existsSync,readdirSync,renameSync } from 'node:fs';
import { dirname,join,relative } from 'node:path';
const slug=text=>text.replace(/[^a-zA-Z0-9]+/g,'-').toLowerCase();
const atomicWrite=(path,content)=>{const temporary=`${path}.${process.pid}.tmp`;writeFileSync(temporary,content);renameSync(temporary,path);};
async function settled(page) {
  await expect(page.locator('main')).toHaveAttribute('data-status','synced');
  if(await page.locator('[data-table-view]').count())await expect(page.locator('[data-table-view]')).toHaveAttribute('data-motion-idle','true');
  await expect(page.locator('.component-flight:visible')).toHaveCount(0);
  // A Firestore update can replace the image nodes while decode() is pending.
  // Inspect the current nodes and their dimensions in the same browser task.
  await expect.poll(()=>page.evaluate(async()=>{
    await document.fonts.ready;
    await Promise.all([...document.images].map(image=>image.decode().catch(()=>{})));
    const pending=[...document.images].filter(image=>!image.complete||!image.naturalWidth||!image.naturalHeight).map(image=>image.alt);
    const enlarged=[...document.querySelectorAll('.painted-token>.painting')].filter(image=>{
      if(!image.naturalWidth)return false;
      const box=image.getBoundingClientRect(),density=window.devicePixelRatio||1;
      return box.width*density>image.naturalWidth+.1||box.height*density>image.naturalHeight+.1;
    }).map(image=>({alt:image.alt,source:[image.naturalWidth,image.naturalHeight]}));
    return {pending,enlarged};
  }),{message:'Current artwork must be decoded, and celebrations must never exceed their native pixels'}).toEqual({pending:[],enlarged:[]});
}
async function stableFrame(page) {
  let previous,identical=0;
  const deadline=Date.now()+10000;
  while(Date.now()<deadline) {
    await settled(page);
    const frame=await page.screenshot({animations:'disabled',caret:'hide',scale:'css',fullPage:true});
    const decoded=PNG.sync.read(frame);
    if(previous&&decoded.width===previous.width&&decoded.height===previous.height&&decoded.data.equals(previous.data))identical++;else identical=0;
    if(identical===2)return frame;
    previous=decoded;await page.waitForTimeout(150);
  }
  throw Error('The rendered page did not settle to three identical RGBA frames.');
}
function writeIndex(root) {
  const stories=[];
  for(const story of readdirSync(join(root,'walkthroughs'),{withFileTypes:true}).filter(e=>e.isDirectory())) {
    for(const platform of readdirSync(join(root,'walkthroughs',story.name),{withFileTypes:true}).filter(e=>e.isDirectory())) {
      const dir=join('walkthroughs',story.name,platform.name),file=join(root,dir,'steps.json');
      if(existsSync(file)){const manifest=JSON.parse(readFileSync(file));stories.push({title:manifest.title,platform:platform.name,steps:manifest.steps.length,manifest:`${dir}/steps.json`,readme:`${dir}/README.md`});}
    }
  }
  stories.sort((a,b)=>a.title.localeCompare(b.title)||a.platform.localeCompare(b.platform));
  atomicWrite(join(root,'walkthroughs','index.json'),JSON.stringify(stories,null,2)+'\n');
  atomicWrite(join(root,'README.md'),`# Browser walkthroughs\n\nGenerated by TestStepHelper from real game interactions. Each step checks viewport bounds, page scrolling and control clipping, with actor/observer screenshots and accessible DOM evidence. Ordinary verification compares every decoded RGBA byte and the complete accessible DOM, with zero tolerance and no masks or retries.\n\n[Open the visual step viewer](${process.env.HANAMI_REVIEW_URL||"https://anicolao.github.io/hanami/review/"}) or serve this folder and open [index.html](index.html).\n\n${stories.map(s=>`- [${s.title} (${s.platform})](${s.readme}) — ${s.steps} steps`).join('\n')}\n`);
}
export class TestStepHelper {
  constructor(info,pages,title){this.info=info;this.pages=pages;this.title=title;this.index=0;this.steps=[];this.id=slug(info.title);}
  async step(description,actor,action,check,{parkMouse=true}={}) {
    await test.step(description,async()=>{
      await action();await check();
      const groups=new Map();
      for(const page of Object.values(this.pages)) {
        await settled(page);
        const code=await page.locator('main').getAttribute('data-table');
        if(code)groups.set(code,[...(groups.get(code)||[]),page]);
      }
      for(const pages of groups.values())await expect.poll(async()=>new Set(await Promise.all(pages.map(p=>p.locator('main').getAttribute('data-revision')))).size).toBe(1);
      const number=String(this.index++).padStart(3,'0'),views=[];
      for(const [name,page] of Object.entries(this.pages)) {
        if(parkMouse){
          // A real mouse click clears Chromium's painted touch-hover state.
          // Use noninteractive paper inside the top layer, never a backdrop
          // (which can dismiss an inspector) or a touch-adjusted corner tap.
          const parking=await page.evaluate(()=>{
            const modal=document.querySelector('dialog:modal')||[...document.querySelectorAll('[role="dialog"][aria-modal="true"]:not([aria-hidden="true"])')].find(el=>el.checkVisibility({visibilityProperty:true,opacityProperty:true}));
            const points=modal?[...modal.querySelectorAll('h1,h2,p')].map(el=>{const b=el.getBoundingClientRect();return[(b.left+b.right)/2,(b.top+b.bottom)/2];}):[[0,0],[innerWidth-1,0],[0,innerHeight-1]];
            return points.map(([x,y])=>({x,y,target:document.elementFromPoint(x,y)})).filter(({target})=>target&&(!modal||modal.contains(target))&&!target.closest('button,a,input,select,textarea,[role="button"],[data-cell],iframe')).map(({x,y})=>({x,y}))[0];
          });
          expect(parking,'Capture housekeeping must target noninteractive paper').toBeTruthy();
          await page.mouse.click(parking.x,parking.y);await page.evaluate(()=>new Promise(requestAnimationFrame));
          await expect.poll(()=>page.locator('button:not(:disabled):hover').evaluateAll(nodes=>nodes.map(el=>el.getAttribute('aria-label')||el.textContent.trim())),{message:'Neutral mouse input must clear button hover'}).toEqual([]);
        }await settled(page);
        const basename=`${number}-${slug(name)}`,file=`${this.id}/${basename}.png`,path=this.info.snapshotPath(file);
        const actual=await stableFrame(page);
        await assertGameFits(page);
        for(const frame of page.frames().filter(frame=>frame!==page.mainFrame()))await assertGameFits(frame);
        // Capture accessibility after the frame settles, including CSS drawer transitions.
        const dom=await page.locator('#app').ariaSnapshot();expect(dom.length).toBeGreaterThan(100);
        if(this.info.config.updateSnapshots==='all'){
          mkdirSync(dirname(path),{recursive:true});writeFileSync(path,actual);writeFileSync(path.replace('.png','.dom.txt'),dom+'\n');
        }else{
          expect(existsSync(path),`Missing reviewed screenshot ${path}`).toBe(true);
          const a=PNG.sync.read(actual),b=PNG.sync.read(readFileSync(path));
          if(a.width!==b.width||a.height!==b.height||!a.data.equals(b.data)){
            await this.info.attach(`${basename}-actual`,{body:actual,contentType:'image/png'});
            expect(actual).toMatchSnapshot(file,{maxDiffPixels:0,threshold:0});
            expect(a.data.equals(b.data),'Every decoded RGBA byte must match').toBe(true);
          }
          expect(dom+'\n').toBe(readFileSync(path.replace('.png','.dom.txt'),'utf8'));
        }
        await this.info.attach(`${basename}-dom`,{body:dom,contentType:'text/plain'});
        const root=dirname(this.info.file);
        views.push({name,image:relative(root,path),dom:relative(root,path.replace('.png','.dom.txt'))});
      }
      this.steps.push({number,description,actor,views});
    });
  }
  finish() {
    const root=dirname(this.info.file),directory=join(root,'walkthroughs',this.id,process.platform);
    const content=`# ${this.title}\n\nReal UI → authenticated Firestore transaction → immutable event → deterministic replay → every observer. Zero pixel tolerance; every decoded RGBA byte and the accessible DOM are compared. No game-state injection or outcome fixtures.\n\n${this.steps.map(s=>`## ${s.number}. ${s.actor}: ${s.description}\n\nViewport, scrolling, clipping and DOM assertions passed; actor and all observers captured.\n\n${s.views.map(v=>`![${v.name}: ${s.description}](../../../${v.image})\n\n[${v.name} DOM evidence](../../../${v.dom})`).join('\n\n')}`).join('\n\n')}\n`;
    if(this.info.config.updateSnapshots==='all'){
      mkdirSync(directory,{recursive:true});atomicWrite(join(directory,'README.md'),content);
      atomicWrite(join(directory,'steps.json'),JSON.stringify({title:this.title,id:this.id,platform:process.platform,steps:this.steps},null,2)+'\n');
      writeIndex(root);
    }else expect(readFileSync(join(directory,'README.md'),'utf8')).toBe(content);
  }
}
